// Card K02 follow-up: the service unit printer's command line. It only prints; it never writes, installs or enables anything.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import { main } from "./nimblenewt-service.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const capture = () => { let out = ""; let err = ""; return { stdout: { write: (t) => { out += t; } }, stderr: { write: (t) => { err += t; } }, get out() { return out; }, get err() { return err; } }; };
const run = async (argv, extra = {}) => { const c = capture(); const code = await main(argv, { stdout: c.stdout, stderr: c.stderr, env: {}, uid: 1000, platform: "linux", ...extra }); return { code, out: c.out, err: c.err }; };

test("print shows the unit and numbered install steps for each platform, and says it installed nothing (K02 service)", async () => {
  const linux = await run(["print", "--platform", "linux", "--root", "/srv/nn root", "--node", "/usr/bin/node", "--launcher", "/opt/nn/nimblenewt-launcher.mjs", "--environment-file", "/home/a/nn.env", "--log-dir", "/home/a/logs", "--", "--serve"]);
  assert.equal(linux.code, 0, linux.err);
  assert.match(linux.out, /THIS PROGRAM INSTALLED NOTHING/);
  assert.match(linux.out, /^ExecStart="\/usr\/bin\/node" "\/opt\/nn\/nimblenewt-launcher\.mjs" "--root" "\/srv\/nn root" .* "--" "--serve"$/m);
  assert.match(linux.out, /systemctl --user enable --now nimblenewt\.service/);
  assert.match(linux.out, /RestartPreventExitStatus=2 3 4/);
  const darwin = await run(["print", "--platform=darwin", "--root", "/Users/a/nn", "--node", "/usr/local/bin/node", "--launcher", "/opt/nn/l.mjs"]);
  assert.equal(darwin.code, 0, darwin.err);
  assert.match(darwin.out, /launchctl bootstrap "gui\/\$\(id -u\)"/);
  assert.match(darwin.out, /<key>SuccessfulExit<\/key>/);
  const win = await run(["print", "--platform", "win32", "--root", "C:\\NN\\root", "--node", "C:\\Program Files\\nodejs\\node.exe", "--launcher", "C:\\NN\\l.mjs", "--windows-user", "PC\\ann"]);
  assert.equal(win.code, 0, win.err);
  assert.match(win.out, /Register-ScheduledTask -TaskName 'nimblenewt' -Xml \$xml/);
  assert.match(win.out, /<RunLevel>LeastPrivilege<\/RunLevel>/);
});

test("--unit-only prints exactly the unit text, and the defaults are this machine's node and the launcher next to the program (K02 service)", async () => {
  const r = await run(["print", "--platform", "linux", "--root", "/srv/nn", "--unit-only"]);
  assert.equal(r.code, 0, r.err);
  assert.ok(r.out.startsWith("# Generated by nimblenewt-service.mjs"));
  assert.ok(!r.out.includes("Install steps"));
  assert.ok(r.out.includes(`"${process.execPath}" "${resolve(here, "nimblenewt-launcher.mjs")}"`));
  const env = await run(["print", "--platform", "linux", "--unit-only"], { env: { NIMBLENEWT_RELEASE_ROOT: "/srv/from-env" } });
  assert.ok(env.out.includes('"--root" "/srv/from-env"'));
});

test("refusals exit 1 with the reason and print no unit: relative or hostile paths, secrets, root, unknown options (K02 service)", async () => {
  for (const [argv, why, extra] of [
    [["print", "--platform", "linux", "--root", "relative"], /root: must be an absolute path/],
    [["print", "--platform", "linux", "--root", "/srv/a\nb"], /control characters/],
    [["print", "--platform", "linux", "--root", "/srv/a/../b"], /normalised/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--node", "node"], /node: must be an absolute path/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--environment-file", "/h/my env"], /envFile/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--", "--api-key=abc"], /credential/],
    [["print", "--platform", "win32", "--root", "C:\\a|b", "--node", "C:\\n.exe", "--launcher", "C:\\l.mjs", "--windows-user", "PC\\ann"], /root/],
    [["print", "--platform", "win32", "--root", "C:\\NN", "--node", "C:\\n.exe", "--launcher", "C:\\l.mjs"], /windowsUser: is required/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--unit-only=no"], /takes no value/],
    [["print", "--platform", "plan9", "--root", "/srv/x"], /platform/],
    [["print", "--platform", "linux"], /--root is required/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--bogus", "1"], /unknown option --bogus/],
    [["print", "--platform", "linux", "--root", "/srv/x", "--root", "/srv/y"], /twice/],
    [["print", "--platform", "linux", "--root"], /needs a value/],
    [["remove", "--root", "/srv/x"], /unknown command/],
    [["print", "--platform", "linux", "--root", "/srv/x"], /ordinary user/, { uid: 0 }],
  ]) {
    const r = await run(argv, extra ?? {});
    assert.equal(r.code, 1, JSON.stringify(argv));
    assert.equal(r.out, "", `nothing is printed for ${JSON.stringify(argv)}`);
    assert.match(r.err, why, JSON.stringify(argv));
  }
});

test("run as a real process: prints, writes nothing in the working directory, and Node does not read --environment-file itself (K02 service)", () => {
  const cwd = mkdtempSync(join(tmpdir(), "nn-svc-"));
  try {
    const p = spawnSync(process.execPath, [join(here, "nimblenewt-service.mjs"), "print", "--platform", "linux", "--root", "/srv/nn", "--environment-file", "/nonexistent/nn.env", "--unit-only"], { cwd, encoding: "utf8" });
    assert.equal(p.status, 0, p.stderr);
    assert.match(p.stdout, /^EnvironmentFile=\/nonexistent\/nn\.env$/m);
    assert.deepEqual(readdirSync(cwd), []);
    const bad = spawnSync(process.execPath, [join(here, "nimblenewt-service.mjs"), "print", "--platform", "linux", "--root", "rel"], { cwd, encoding: "utf8" });
    assert.equal(bad.status, 1);
    assert.equal(bad.stdout, "");
  } finally { rmSync(cwd, { recursive: true, force: true }); }
});
