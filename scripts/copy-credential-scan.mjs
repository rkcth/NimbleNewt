// The credential scanner lives in packages/controller/src/security (credential-patterns, secret-scan, redact, clean). The config, worker and pi-adapter packages may not import the controller (package
// boundaries: config imports nothing, the worker and pi-adapter only contracts), so the same code is COPIED as ONE file into contracts and config. This script writes the copies; `--check` says whether
// they are current (a test runs it, so a copy cannot drift from the original). Edit the controller files, then run `node scripts/copy-credential-scan.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../packages/", import.meta.url));
const SOURCES = ["credential-patterns", "secret-scan", "redact", "clean"];
export const COPIES = ["contracts/src/credential-scan.ts", "config/src/credential-scan.ts"];

export function build() {
  const parts = SOURCES.map((name) => readFileSync(`${root}controller/src/security/${name}.ts`, "utf8")
    // one-line relative imports of the other scanner files go: everything is in this one file
    .replace(/^import [^\n]*from "\.\/[a-z-]+\.js";\n/gm, "")
    .replace(/^export \{ REDACTED \};\n/gm, "")
    .trim());
  return `// GENERATED by scripts/copy-credential-scan.mjs from packages/controller/src/security/{${SOURCES.join(",")}}.ts. Do not edit: change the controller files and run the script.\n// Copied because this package may not import the controller (scripts/package-boundaries.mjs); a test checks that the copy is current.\n\n${parts.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes("--check")) {
    const stale = COPIES.filter((c) => { try { return readFileSync(`${root}${c}`, "utf8") !== text; } catch { return true; } });
    if (stale.length > 0) { console.error(`stale credential scanner copies: ${stale.join(", ")}; run node scripts/copy-credential-scan.mjs`); process.exit(1); }
  } else for (const c of COPIES) writeFileSync(`${root}${c}`, text);
}
